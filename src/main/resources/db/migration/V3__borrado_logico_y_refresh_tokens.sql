CREATE TABLE refresh_tokens (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token_hash varchar(64) NOT NULL UNIQUE, usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE, familia uuid NOT NULL, expires_at timestamp(6) WITH TIME ZONE NOT NULL, revocado boolean NOT NULL DEFAULT false);
CREATE INDEX idx_refresh_usuario ON refresh_tokens(usuario_id);
CREATE INDEX idx_refresh_familia ON refresh_tokens(familia);
CREATE INDEX idx_refresh_expiracion ON refresh_tokens(expires_at);
